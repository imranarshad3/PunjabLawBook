#!/usr/bin/env node
/**
 * Generates supabase/seed.sql from the repository catalogue so the database
 * starts with the same titles, subjects and collections the storefront shows.
 * Re-runnable: every statement upserts.
 */
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");

const catalogue = JSON.parse(read("src/data/catalogue.json"));
const productsSrc = read("src/data/products.ts");
const collectionsSrc = read("src/data/collections.ts");

// subjects map: { 6078: "Exam Guides", ... }
const subjects = {};
const subjectBlock = productsSrc.match(/subjects[^=]*=\s*{([\s\S]*?)};/);
for (const [, id, name] of (subjectBlock?.[1] || "").matchAll(/(\d+):\s*"([^"]+)"/g)) {
  subjects[Number(id)] = name;
}

const books = [...catalogue.featured, ...catalogue.bestsellers].filter(
  (book, index, all) => all.findIndex((other) => other.id === book.id) === index,
);

const collections = [];
for (const [, slug, title, description, ids] of collectionsSrc.matchAll(
  /"([a-z-]+)":\s*{\s*title:\s*"([^"]*)",\s*description:\s*"([^"]*)",\s*ids:\s*\[([^\]]*)\]/g,
)) {
  collections.push({
    slug,
    title,
    description,
    ids: ids.split(",").map((value) => Number(value.trim())).filter(Boolean),
  });
}

const pages = [
  ["homepage", "Homepage", "/", "Hero, trust highlights, categories, featured titles, bestsellers, exam guides and bookstore story."],
  ["about", "About the bookstore", "/about", "The Punjab Law Book House introduction and brand story."],
  ["contact", "Contact", "/contact", "Store location, telephone numbers and WhatsApp enquiries."],
  ["request-a-book", "Request a book", "/request-a-book", "Book title, edition, quantity and notes prepared for WhatsApp."],
  ["delivery", "Delivery", "/delivery", "Delivery information and ordering guidance."],
  ["returns", "Returns & support", "/returns", "Return and customer support information."],
  ["help", "Ordering help", "/help", "Guidance for book selection and ordering."],
  ["privacy", "Privacy", "/privacy", "The storefront privacy information page."],
];

const slugify = (value) =>
  value
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60) || "book";

const q = (value) =>
  value === null || value === undefined ? "null" : `'${String(value).replaceAll("'", "''")}'`;

const out = [];
out.push("-- Generated by scripts/generate-seed.cjs — do not edit by hand.");
out.push("-- Seeds the real storefront catalogue. Safe to re-run.");
out.push("begin;");
out.push("");

out.push("-- categories");
const categoryNames = [...new Set(Object.values(subjects))];
categoryNames.forEach((name, index) => {
  out.push(
    `insert into public.categories (slug, name, sort_order) values (${q(slugify(name))}, ${q(name)}, ${index}) ` +
      "on conflict (slug) do update set name = excluded.name, sort_order = excluded.sort_order;",
  );
});
out.push("");

out.push("-- books");
for (const book of books) {
  const category = subjects[book.id];
  const categoryRef = category
    ? `(select id from public.categories where slug = ${q(slugify(category))})`
    : "null";
  out.push(
    "insert into public.books (legacy_id, slug, title, category_id, price, stock, status, cover_url) values (" +
      [
        book.id,
        q(`${slugify(book.name)}-${book.id}`),
        q(book.name),
        categoryRef,
        Number(book.price).toFixed(2),
        // null = stock not counted yet; 0 = known to be unavailable
        book.inStock ? "null" : "0",
        q("published"),
        q(book.image),
      ].join(", ") +
      ") on conflict (legacy_id) do update set " +
      "title = excluded.title, category_id = excluded.category_id, price = excluded.price, " +
      "cover_url = excluded.cover_url, status = excluded.status;",
  );
}
out.push("");

out.push("-- cover assets");
out.push(
  "insert into public.media_assets (book_id, url, alt_text, kind) " +
    "select b.id, b.cover_url, b.title, 'cover' from public.books b " +
    "where b.cover_url is not null and not exists (" +
    "select 1 from public.media_assets m where m.book_id = b.id and m.url = b.cover_url);",
);
out.push("");

out.push("-- collections");
collections.forEach((collection, index) => {
  out.push(
    `insert into public.collections (slug, title, description, sort_order) values (${q(collection.slug)}, ${q(collection.title)}, ${q(collection.description)}, ${index}) ` +
      "on conflict (slug) do update set title = excluded.title, description = excluded.description;",
  );
  for (const [position, id] of collection.ids.entries()) {
    out.push(
      "insert into public.collection_books (collection_id, book_id, sort_order) select c.id, b.id, " +
        `${position} from public.collections c, public.books b where c.slug = ${q(collection.slug)} and b.legacy_id = ${id} ` +
        "on conflict (collection_id, book_id) do update set sort_order = excluded.sort_order;",
    );
  }
});
out.push("");

out.push("-- homepage sections");
for (const [index, [key, title]] of [
  ["featured", "Featured titles"],
  ["bestsellers", "Bestsellers"],
].entries()) {
  out.push(
    `insert into public.featured_sections (key, title, sort_order) values (${q(key)}, ${q(title)}, ${index}) ` +
      "on conflict (key) do update set title = excluded.title;",
  );
  for (const [position, book] of catalogue[key].entries()) {
    out.push(
      "insert into public.featured_section_books (section_id, book_id, sort_order) select s.id, b.id, " +
        `${position} from public.featured_sections s, public.books b where s.key = ${q(key)} and b.legacy_id = ${book.id} ` +
        "on conflict (section_id, book_id) do update set sort_order = excluded.sort_order;",
    );
  }
}
out.push("");

out.push("-- storefront pages");
for (const [slug, title, path_, description] of pages) {
  out.push(
    `insert into public.content_pages (slug, title, path, description) values (${q(slug)}, ${q(title)}, ${q(path_)}, ${q(description)}) ` +
      "on conflict (slug) do update set title = excluded.title, path = excluded.path, description = excluded.description;",
  );
}
out.push("");

out.push("-- store settings (single row)");
out.push(
  "insert into public.store_settings (id, store_name, city, country, currency, payment_methods) " +
    "values (true, 'Punjab Law Book House', 'Lahore', 'Pakistan', 'PKR', array['cash_on_delivery']) " +
    "on conflict (id) do nothing;",
);
out.push("");
out.push("commit;");

fs.writeFileSync(path.join(root, "supabase/seed.sql"), out.join("\n") + "\n");
console.log(
  `seed.sql written: ${categoryNames.length} categories, ${books.length} books, ${collections.length} collections, ${pages.length} pages`,
);
